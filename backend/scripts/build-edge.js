// ============================================================
// Build the Supabase Edge Function from this backend.
//   npm run build:edge
// Bundles edge-entry.js and everything it uses (Express, pg,
// nodemailer...) into one file Supabase can run:
//   ../supabase/functions/api/server.bundle.js
// ============================================================

const path = require('path');
const fs = require('fs');
const esbuild = require('esbuild');

const root = path.join(__dirname, '..');
const outFile = path.join(root, '..', 'supabase', 'functions', 'api', 'server.bundle.js');

// Keep the bundled email logo in step with the PNG
const png = path.join(root, 'assets', 'email', 'logo-mark.png');
if (fs.existsSync(png)) {
    fs.writeFileSync(
        path.join(root, 'assets', 'email', 'logo.js'),
        "// The email logo (logo-mark.png) as base64, so it's bundled into the\n// Supabase Edge Function, which has no files of its own.\n// Regenerate after changing the PNG: npm run build:edge does it.\nmodule.exports = '" + fs.readFileSync(png).toString('base64') + "';\n"
    );
}

esbuild.build({
    entryPoints: [path.join(root, 'edge-entry.js')],
    outfile: outFile,
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'es2022',
    minify: false,
    legalComments: 'none',
    // Optional native/legacy drivers we never use on Supabase
    external: ['pg-native', 'oracledb', 'mongoose', 'cloudflare:sockets'],
    banner: {
        js: [
            '// Generated by backend/scripts/build-edge.js. Do not edit; edit backend/ and rebuild.',
            "import { createRequire as __cr } from 'node:module';",
            "import { fileURLToPath as __fu } from 'node:url';",
            "import { dirname as __dn } from 'node:path';",
            "import { Buffer as __Buffer } from 'node:buffer';",
            "import __process from 'node:process';",
            "import { setImmediate as __si, clearImmediate as __ci } from 'node:timers';",
            // Node globals Express, pg and nodemailer expect
            'globalThis.Buffer ??= __Buffer; globalThis.process ??= __process; globalThis.global ??= globalThis;',
            'globalThis.setImmediate ??= __si; globalThis.clearImmediate ??= __ci;',
            // Supabase's hosted runtime refuses to change environment variables
            // (process.env.X = ... throws "NotSupported"). Libraries like debug
            // do that, so writes that fail are kept in memory instead.
            '(() => { const p = globalThis.process; const real = p.env; const over = new Map(); const DEL = Symbol("deleted");',
            '  const has = (k) => (over.has(k) ? over.get(k) !== DEL : k in real);',
            '  const val = (k) => (over.has(k) ? (over.get(k) === DEL ? undefined : over.get(k)) : real[k]);',
            '  const env = new Proxy({}, {',
            '    get: (_, k) => (typeof k === "string" ? val(k) : undefined),',
            '    set: (_, k, v) => { try { real[k] = String(v); over.delete(k); } catch { over.set(k, String(v)); } return true; },',
            '    deleteProperty: (_, k) => { try { delete real[k]; over.delete(k); } catch { over.set(k, DEL); } return true; },',
            '    has: (_, k) => typeof k === "string" && has(k),',
            '    ownKeys: () => { const keys = new Set([...Object.keys(real), ...over.keys()]); for (const [k, v] of over) if (v === DEL) keys.delete(k); return [...keys]; },',
            '    getOwnPropertyDescriptor: (_, k) => (typeof k === "string" && has(k) ? { value: val(k), writable: true, enumerable: true, configurable: true } : undefined)',
            '  });',
            '  try { Object.defineProperty(p, "env", { value: env, writable: true, configurable: true }); } catch { try { p.env = env; } catch {} }',
            '})();',
            'const require = __cr(import.meta.url);',
            'const __filename = __fu(import.meta.url);',
            'const __dirname = __dn(__filename);'
        ].join('\n')
    },
    logLevel: 'info'
}).then(() => {
    const kb = Math.round(fs.statSync(outFile).size / 1024);
    console.log(`\nBuilt supabase/functions/api/server.bundle.js (${kb} KB)`);
}).catch(() => process.exit(1));
