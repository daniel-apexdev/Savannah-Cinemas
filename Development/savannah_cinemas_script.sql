CREATE TABLE PROMOTIONS (

    PROMOTION_ID NUMBER
        GENERATED BY DEFAULT AS IDENTITY,

    PROMOTION_CODE VARCHAR2(50)
        NOT NULL,

    PROMOTION_NAME VARCHAR2(150)
        NOT NULL,

    DESCRIPTION VARCHAR2(500),

    DISCOUNT_TYPE VARCHAR2(20)
        NOT NULL,

    DISCOUNT_VALUE NUMBER(10,2)
        NOT NULL,

    MINIMUM_AMOUNT NUMBER(10,2),

    MAX_DISCOUNT_AMOUNT NUMBER(10,2),

    START_DATE TIMESTAMP(6)
        NOT NULL,

    END_DATE TIMESTAMP(6)
        NOT NULL,

    USAGE_LIMIT NUMBER,

    USAGE_COUNT NUMBER
        DEFAULT 0
        NOT NULL,

    IS_ACTIVE CHAR(1)
        DEFAULT 'Y'
        NOT NULL,

    CREATED_AT TIMESTAMP(6)
        DEFAULT CURRENT_TIMESTAMP
        NOT NULL,

    UPDATED_AT TIMESTAMP(6),

    CONSTRAINT PK_PROMOTIONS
        PRIMARY KEY (PROMOTION_ID),

    CONSTRAINT UQ_PROMOTIONS_CODE
        UNIQUE (PROMOTION_CODE),

    CONSTRAINT CK_PROMOTIONS_TYPE
        CHECK (
            DISCOUNT_TYPE IN (
                'PERCENTAGE',
                'FIXED'
            )
        ),

    CONSTRAINT CK_PROMOTIONS_VALUE
        CHECK (DISCOUNT_VALUE >= 0),

    CONSTRAINT CK_PROMOTIONS_USAGE
        CHECK (
            USAGE_LIMIT IS NULL
            OR USAGE_LIMIT >= 0
        ),

    CONSTRAINT CK_PROMOTIONS_ACTIVE
        CHECK (IS_ACTIVE IN ('Y','N')),

    CONSTRAINT CK_PROMOTIONS_DATES
        CHECK (END_DATE >= START_DATE)

);



CREATE TABLE PROMOTION_USAGE (

    PROMOTION_USAGE_ID NUMBER
        GENERATED BY DEFAULT AS IDENTITY,

    PROMOTION_ID NUMBER
        NOT NULL,

    USER_ID NUMBER
        NOT NULL,

    BOOKING_ID NUMBER
        NOT NULL,

    DISCOUNT_AMOUNT NUMBER(10,2)
        NOT NULL,

    USED_AT TIMESTAMP(6)
        DEFAULT CURRENT_TIMESTAMP
        NOT NULL,

    CONSTRAINT PK_PROMOTION_USAGE
        PRIMARY KEY (PROMOTION_USAGE_ID),

    CONSTRAINT FK_PROMO_USAGE_PROMOTION
        FOREIGN KEY (PROMOTION_ID)
        REFERENCES PROMOTIONS(PROMOTION_ID),

    CONSTRAINT FK_PROMO_USAGE_USER
        FOREIGN KEY (USER_ID)
        REFERENCES USERS(USER_ID),

    CONSTRAINT FK_PROMO_USAGE_BOOKING
        FOREIGN KEY (BOOKING_ID)
        REFERENCES BOOKINGS(BOOKING_ID),

    CONSTRAINT CK_PROMO_USAGE_AMOUNT
        CHECK (DISCOUNT_AMOUNT >= 0),

    CONSTRAINT UQ_PROMO_USAGE_BOOKING
        UNIQUE (BOOKING_ID)

);














