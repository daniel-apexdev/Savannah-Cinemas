-- Trigger to automatically calculate END_TIME from START_TIME + movie runtime
CREATE OR REPLACE TRIGGER TRG_SHOWTIMES_END_TIME
BEFORE INSERT OR UPDATE OF START_TIME, MOVIE_ID ON SHOWTIMES
FOR EACH ROW
DECLARE
    v_runtime NUMBER;
BEGIN
    -- Get movie runtime in minutes
    SELECT RUNTIME_MINUTES 
    INTO v_runtime 
    FROM MOVIES 
    WHERE MOVIE_ID = :NEW.MOVIE_ID;
    
    -- Calculate END_TIME
    IF v_runtime IS NOT NULL AND :NEW.START_TIME IS NOT NULL THEN
        :NEW.END_TIME := :NEW.START_TIME + (v_runtime / 1440); -- 1440 minutes in a day
    END IF;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        -- If movie not found, don't set END_TIME
        NULL;
END;
/

