-- Sample data for a screen with 5 rows (A-E) and 10 seats per row
INSERT INTO SEATS (SCREEN_ID, ROW_LABEL, SEAT_NUMBER, SEAT_LABEL, SEAT_TYPE)
SELECT 
    1,  -- Screen ID
    CHR(64 + ROW_NUMBER) as ROW_LABEL,  -- A, B, C, D, E
    COLUMN_NUMBER as SEAT_NUMBER,
    CHR(64 + ROW_NUMBER) || TO_CHAR(COLUMN_NUMBER) as SEAT_LABEL,
    CASE 
        WHEN COLUMN_NUMBER IN (1, 10) THEN 'STANDARD'  -- Aisle seats
        WHEN COLUMN_NUMBER IN (5, 6) THEN 'VIP'        -- Center seats
        ELSE 'STANDARD'
    END as SEAT_TYPE
FROM (
    SELECT LEVEL as ROW_NUMBER 
    FROM DUAL 
    CONNECT BY LEVEL <= 5
) ROWS
CROSS JOIN (
    SELECT LEVEL as COLUMN_NUMBER 
    FROM DUAL 
    CONNECT BY LEVEL <= 10
) COLUMNS
ORDER BY ROW_NUMBER, COLUMN_NUMBER;

