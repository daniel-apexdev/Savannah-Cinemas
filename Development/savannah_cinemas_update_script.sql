CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at := CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

DO $$
DECLARE
    t TEXT;
BEGIN
    FOREACH t IN ARRAY ARRAY[
        'customer_profiles','staff_profiles','cinemas','screens','studios','genres',
        'people','movies','production_companies','showtimes','ticket_prices',
        'promotions','bookings','payments','tickets','movie_reviews',
        'user_preferences','user_notification_preferences'
    ] LOOP
        EXECUTE format('DROP TRIGGER IF EXISTS trg_%I_updated_at ON %I',t,t);
        EXECUTE format('CREATE TRIGGER trg_%I_updated_at BEFORE UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION set_updated_at()',t,t);
    END LOOP;
END $$;

-- ============================================================
-- MOVIE STATUS FUNCTION
-- ============================================================
CREATE OR REPLACE FUNCTION calculate_movie_status(p_release_date DATE)
RETURNS VARCHAR(30)
LANGUAGE plpgsql
AS $$
BEGIN
    IF p_release_date IS NULL THEN
        RETURN 'UPCOMING';
    ELSIF p_release_date > CURRENT_DATE THEN
        RETURN 'UPCOMING';
    ELSIF EXTRACT(YEAR FROM p_release_date) = EXTRACT(YEAR FROM CURRENT_DATE) THEN
        RETURN 'NOW_SHOWING';
    ELSIF p_release_date < CURRENT_DATE THEN
        RETURN 'ENDED';
    END IF;
    RETURN 'UPCOMING';
END;
$$;

CREATE OR REPLACE FUNCTION trg_movies_status()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.status := calculate_movie_status(NEW.release_date);
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_movies_status
BEFORE INSERT OR UPDATE OF release_date ON movies
FOR EACH ROW EXECUTE FUNCTION trg_movies_status();

-- ============================================================
-- SHOWTIME END TIME
-- ============================================================
CREATE OR REPLACE FUNCTION calculate_showtime_end()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_runtime INTEGER;
BEGIN
    SELECT runtime_minutes INTO v_runtime
    FROM movies
    WHERE movie_id = NEW.movie_id;

    IF v_runtime IS NOT NULL AND NEW.start_time IS NOT NULL THEN
        NEW.end_time := NEW.start_time + make_interval(mins => v_runtime);
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_showtimes_end_time
BEFORE INSERT OR UPDATE OF start_time,movie_id ON showtimes
FOR EACH ROW EXECUTE FUNCTION calculate_showtime_end();

-- ============================================================
-- BOOKING TOTAL
-- ============================================================
CREATE OR REPLACE FUNCTION calculate_booking_total()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.total_amount := GREATEST((NEW.ticket_quantity * NEW.ticket_price) - COALESCE(NEW.discount_amount,0),0);
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_bookings_total
BEFORE INSERT OR UPDATE OF ticket_quantity,ticket_price,discount_amount ON bookings
FOR EACH ROW EXECUTE FUNCTION calculate_booking_total();

