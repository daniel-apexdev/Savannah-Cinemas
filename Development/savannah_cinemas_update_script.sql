CREATE OR REPLACE FUNCTION update_payment_date()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.status = 'COMPLETED' AND COALESCE(OLD.status,'') <> 'COMPLETED' THEN
        NEW.payment_date := CURRENT_TIMESTAMP;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_payments_completed
BEFORE UPDATE ON payments
FOR EACH ROW EXECUTE FUNCTION update_payment_date();

