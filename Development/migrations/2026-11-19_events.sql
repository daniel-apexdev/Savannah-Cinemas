-- ============================================================
-- SAVANNAH CINEMAS - EVENTS
-- 2026-11-19_events.sql
--
-- Events shown on the app's Events tab (with the live promotions and
-- the coming-soon opening days). An event is either one-off
-- (starts_at) or weekly (weekday 1=Mon..7=Sun + start_time), and can
-- point at a film (movie_id) so the app links to it.
--
-- The two rows below are SAMPLES to show the layout. Edit them,
-- deactivate them (is_active = FALSE) or delete them.
-- Safe to run more than once.
-- ============================================================

CREATE TABLE IF NOT EXISTS cinema_events (
    event_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cinema_id   BIGINT REFERENCES cinemas(cinema_id),
    title       VARCHAR(150) NOT NULL,
    summary     VARCHAR(300),
    details     VARCHAR(2000),
    tag         VARCHAR(30),
    starts_at   TIMESTAMP,
    weekday     SMALLINT,
    start_time  TIME,
    ends_on     DATE,
    movie_id    BIGINT REFERENCES movies(movie_id) ON DELETE SET NULL,
    sort_order  INTEGER DEFAULT 0 NOT NULL,
    is_active   BOOLEAN DEFAULT TRUE NOT NULL,
    created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT ck_cinema_events_when CHECK (starts_at IS NOT NULL OR (weekday BETWEEN 1 AND 7 AND start_time IS NOT NULL))
);

CREATE INDEX IF NOT EXISTS idx_cinema_events_active ON cinema_events (is_active, starts_at);

INSERT INTO cinema_events (cinema_id, title, summary, details, tag, weekday, start_time, sort_order)
SELECT c.cinema_id, e.title, e.summary, e.details, e.tag, e.weekday, e.start_time::time, e.sort_order
FROM (SELECT cinema_id FROM cinemas WHERE cinema_name ILIKE '%Accra%' ORDER BY cinema_id LIMIT 1) c
CROSS JOIN (VALUES
    ('Family Saturday Mornings',
     'Saturday mornings lean towards family films.',
     'Saturday''s first shows favour films rated G and PG, so it''s an easy morning out with the kids. Book as usual from Tonight or Films. (Sample event: edit or delete in cinema_events.)',
     'FAMILY', 6, '10:00', 10),
    ('Late Night Thrillers',
     'Friday''s last shows are for grown-ups.',
     'The late Friday shows lean towards R and 18-rated films. Bring ID: staff may check it at the door. (Sample event: edit or delete in cinema_events.)',
     'LATE NIGHT', 5, '22:00', 20)
) AS e(title, summary, details, tag, weekday, start_time, sort_order)
WHERE NOT EXISTS (SELECT 1 FROM cinema_events x WHERE x.title = e.title);
