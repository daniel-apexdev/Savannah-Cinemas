-- ============================================================
-- SAVANNAH CINEMAS - NOTIFICATIONS & FILM REMINDERS
-- 2026-11-21_notifications.sql
--
-- user_notifications  the in-app inbox (bell in Account). Rows are
--                     created by services/notifications.js:
--                     booking reminders (3 h and 30 min before),
--                     opening-day / on-sale alerts for films a member
--                     asked to be reminded about, new trophies.
-- film_reminders      "remind me" on coming-soon films (bell icon).
-- Safe to run more than once.
-- ============================================================

CREATE TABLE IF NOT EXISTS user_notifications (
    notification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    kind            VARCHAR(30) NOT NULL,
    title           VARCHAR(160) NOT NULL,
    body            VARCHAR(500),
    data            JSONB DEFAULT '{}'::jsonb NOT NULL,
    dedupe_key      VARCHAR(160) NOT NULL,
    deliver_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    read_at         TIMESTAMP,
    CONSTRAINT uk_user_notifications_dedupe UNIQUE (user_id, dedupe_key)
);

CREATE INDEX IF NOT EXISTS idx_user_notifications_inbox
    ON user_notifications (user_id, deliver_at DESC);

CREATE TABLE IF NOT EXISTS film_reminders (
    user_id     BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    movie_id    BIGINT NOT NULL REFERENCES movies(movie_id) ON DELETE CASCADE,
    created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    PRIMARY KEY (user_id, movie_id)
);
