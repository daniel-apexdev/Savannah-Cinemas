-- 2. Options --------------------------------------------------------

CREATE TABLE IF NOT EXISTS concession_options (
    option_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id      BIGINT REFERENCES concession_items(item_id) ON DELETE CASCADE,
    category     VARCHAR(40),
    group_code   VARCHAR(20)   NOT NULL,
    name         VARCHAR(60)   NOT NULL,
    price_delta  NUMERIC(10,2) NOT NULL DEFAULT 0,
    is_default   BOOLEAN       NOT NULL DEFAULT FALSE,
    is_available BOOLEAN       NOT NULL DEFAULT TRUE,
    sort_order   INTEGER       NOT NULL DEFAULT 0,
    CONSTRAINT ck_concession_options_group  CHECK (group_code IN ('SIZE', 'FLAVOUR', 'DRINK', 'EXTRA')),
    CONSTRAINT ck_concession_options_target CHECK ((item_id IS NULL) <> (category IS NULL)),
    CONSTRAINT ck_concession_options_delta  CHECK (price_delta >= 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_concession_options_item
    ON concession_options (COALESCE(item_id, 0), COALESCE(category, ''), group_code, name);

