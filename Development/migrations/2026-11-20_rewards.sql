-- ============================================================
-- SAVANNAH CINEMAS - REWARDS (points, trophies, referrals)
-- 2026-11-20_rewards.sql
--
-- Points are worked out from bookings by services/rewards.js, so
-- cancelling a booking takes its points away and refunds any points
-- spent on it automatically. This migration adds what can't be
-- worked out:
--   - users.referral_code      each member's code to share
--   - referrals                who brought whom
--   - user_trophies            trophies once earned are kept
--   - bookings.points_redeemed / points_discount   points spent at checkout
--   - movies.collection_* / production_countries / original_language
--                              (filled by the TMDB sync) for the
--                              Franchise Fan and Made in Ghana trophies
-- Safe to run more than once.
-- ============================================================

ALTER TABLE users ADD COLUMN IF NOT EXISTS referral_code VARCHAR(16);
CREATE UNIQUE INDEX IF NOT EXISTS uk_users_referral_code ON users (referral_code);

CREATE TABLE IF NOT EXISTS referrals (
    referral_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    referrer_id  BIGINT NOT NULL REFERENCES users(user_id),
    referred_id  BIGINT NOT NULL UNIQUE REFERENCES users(user_id),
    created_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT ck_referrals_self CHECK (referrer_id <> referred_id)
);
CREATE INDEX IF NOT EXISTS idx_referrals_referrer ON referrals (referrer_id);

CREATE TABLE IF NOT EXISTS user_trophies (
    user_id     BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    trophy_code VARCHAR(40) NOT NULL,
    earned_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    booking_id  BIGINT REFERENCES bookings(booking_id) ON DELETE SET NULL,
    seen_at     TIMESTAMP,
    PRIMARY KEY (user_id, trophy_code)
);

ALTER TABLE bookings ADD COLUMN IF NOT EXISTS points_redeemed INTEGER DEFAULT 0 NOT NULL;
ALTER TABLE bookings ADD COLUMN IF NOT EXISTS points_discount NUMERIC(10,2) DEFAULT 0 NOT NULL;

ALTER TABLE movies ADD COLUMN IF NOT EXISTS collection_id INTEGER;
ALTER TABLE movies ADD COLUMN IF NOT EXISTS collection_name VARCHAR(200);
ALTER TABLE movies ADD COLUMN IF NOT EXISTS production_countries VARCHAR(200);
ALTER TABLE movies ADD COLUMN IF NOT EXISTS original_language VARCHAR(10);
CREATE INDEX IF NOT EXISTS idx_movies_collection ON movies (collection_id);
