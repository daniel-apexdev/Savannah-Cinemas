-- ------------------------------------------------------------
-- 3. Orders (always tied to a booking)
--    source BOOKING : added before payment; status follows the booking
--    source PREORDER: bought later for a paid booking; own status
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS concession_orders (
    order_id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id            BIGINT NOT NULL REFERENCES bookings(booking_id) ON DELETE CASCADE,
    user_id               BIGINT NOT NULL REFERENCES users(user_id),
    source                VARCHAR(20) NOT NULL,
    status                VARCHAR(20) NOT NULL,
    total_amount          NUMERIC(10,2) NOT NULL,
    payment_method        VARCHAR(30),
    transaction_reference VARCHAR(100),
    collection_code       VARCHAR(20) NOT NULL,
    created_at            TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    paid_at               TIMESTAMP,
    collected_at          TIMESTAMP,
    CONSTRAINT ck_concession_orders_source CHECK (source IN ('BOOKING','PREORDER')),
    CONSTRAINT ck_concession_orders_status CHECK (status IN ('ATTACHED','PAID','CANCELLED','COLLECTED')),
    CONSTRAINT ck_concession_orders_total CHECK (total_amount >= 0)
);

CREATE INDEX IF NOT EXISTS idx_concession_orders_booking ON concession_orders(booking_id);
CREATE INDEX IF NOT EXISTS idx_concession_orders_user    ON concession_orders(user_id);

CREATE TABLE IF NOT EXISTS concession_order_items (
    order_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      BIGINT NOT NULL REFERENCES concession_orders(order_id) ON DELETE CASCADE,
    item_id       BIGINT NOT NULL REFERENCES concession_items(item_id),
    item_name     VARCHAR(120) NOT NULL,
    unit_price    NUMERIC(10,2) NOT NULL,
    quantity      INTEGER NOT NULL,
    line_total    NUMERIC(10,2) NOT NULL,
    CONSTRAINT ck_concession_order_items_qty CHECK (quantity > 0)
);

CREATE INDEX IF NOT EXISTS idx_concession_order_items_order ON concession_order_items(order_id);
