-- ------------------------------------------------------------
-- 1. Let released seats be booked again
--
-- uk_booking_showtime_seat (showtime_id, seat_id) blocked any new
-- booking of a seat whose earlier booking was CANCELLED or whose
-- unpaid hold had EXPIRED, because those booking_seats rows are
-- kept for history. createBooking() now takes a per-showtime
-- advisory lock and checks live bookings itself, so the constraint
-- is replaced by a plain index.
-- ------------------------------------------------------------

ALTER TABLE booking_seats
    DROP CONSTRAINT IF EXISTS uk_booking_showtime_seat;

CREATE INDEX IF NOT EXISTS idx_booking_seats_showtime_seat
    ON booking_seats(showtime_id, seat_id);


-- ------------------------------------------------------------
-- 2. Concession menu
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS concession_items (
    item_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(120) NOT NULL UNIQUE,
    category     VARCHAR(40)  NOT NULL,
    description  VARCHAR(255),
    price        NUMERIC(10,2) NOT NULL,
    currency     VARCHAR(3)   DEFAULT 'GHS' NOT NULL,
    image_path   VARCHAR(500),
    is_available BOOLEAN      DEFAULT TRUE NOT NULL,
    sort_order   INTEGER      DEFAULT 0 NOT NULL,
    created_at   TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at   TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT ck_concession_items_price CHECK (price >= 0),
    CONSTRAINT ck_concession_items_category CHECK (category IN ('POPCORN','DRINKS','SNACKS','COMBOS'))
);

