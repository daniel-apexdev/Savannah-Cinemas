#!/usr/bin/env python3
"""
Builds supabase/migrations/20261124120000_savannah_cinemas.sql from:
  Development/savannah_cinemas_update_script.sql  (without its DROP block)
  Development/migrations/*.sql                     (in order)
  supabase/supabase_setup.sql                      (Supabase sign-in link + lock-down)
and records the Development migrations in schema_migrations, so
`npm run db:migrate` against Supabase knows they're already applied.

Run from the repo root:  python supabase/build-migration.py
"""
import hashlib, os, re, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
dev = os.path.join(root, 'Development')
out = os.path.join(root, 'supabase', 'migrations', '20261124120000_savannah_cinemas.sql')

def read(p):
    with open(p, encoding='utf-8') as f:
        return f.read().replace('\r\n', '\n')

base = read(os.path.join(dev, 'savannah_cinemas_update_script.sql'))
# Drop the "wipe everything" block: never on Supabase
base, n = re.subn(r'DROP TABLE IF EXISTS\b.*?CASCADE;\n', '-- (DROP block removed for Supabase)\n', base, count=1, flags=re.S)
if n != 1:
    sys.exit('Could not find the DROP block in the setup script')

mig_dir = os.path.join(dev, 'migrations')
files = sorted(f for f in os.listdir(mig_dir) if f.lower().endswith('.sql'))

parts = [
    '-- ============================================================',
    '-- SAVANNAH CINEMAS ON SUPABASE: full database',
    '-- Generated by supabase/build-migration.py. Do not edit by hand.',
    '--',
    '-- Contents:',
    '--   1. Development/savannah_cinemas_update_script.sql (tables + sample data)',
    *[f'--   2. Development/migrations/{f}' for f in files],
    '--   3. supabase/supabase_setup.sql (sign-in link, security)',
    '-- ============================================================',
    '',
    '-- 1. Base schema ----------------------------------------------',
    base,
]

checks = []
for f in files:
    sql = read(os.path.join(mig_dir, f))
    checks.append((f, hashlib.sha256(sql.encode('utf-8')).hexdigest()[:16]))
    parts += ['', f'-- 2. {f} ' + '-' * max(4, 50 - len(f)), sql]

parts += ['', '-- 3. Supabase ---------------------------------------------------', read(os.path.join(root, 'supabase', 'supabase_setup.sql'))]

parts += [
    '',
    '-- Record the Development migrations as applied (npm run db:migrate) --',
    'CREATE TABLE IF NOT EXISTS schema_migrations (',
    '    filename   VARCHAR(255) PRIMARY KEY,',
    '    checksum   VARCHAR(64)  NOT NULL,',
    '    applied_at TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL',
    ');',
    'ALTER TABLE schema_migrations ENABLE ROW LEVEL SECURITY;',
    'INSERT INTO schema_migrations (filename, checksum) VALUES',
    ',\n'.join(f"    ('{f}', '{c}')" for f, c in checks),
    'ON CONFLICT (filename) DO NOTHING;',
    '',
]

os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, 'w', encoding='utf-8', newline='\n') as fh:
    fh.write('\n'.join(parts))
print(f'Wrote {os.path.relpath(out, root)} ({len(files)} migrations)')
